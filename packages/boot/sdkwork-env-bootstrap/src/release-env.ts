/**
 * Packaged-release SDKWork environment: the private values a deployment build
 * carries so an installed desktop application resolves the same SDKWork
 * deployment, and the same bootstrap credential, that the packaging host
 * resolved locally.
 *
 * The artifact is an env file inside the packaged application's private
 * resources. It is not a public artifact: `ENVIRONMENT_SPEC.md` section 6.1.1
 * requires a deployment build that carries the bootstrap credential to stay
 * with that deployment's machines, and forbids the credential in browser
 * artifacts, tracked files, and public configuration.
 * @module @deepseek-ai/dsh-sdkwork-env-bootstrap/release-env
 */

import { readFileSync } from 'node:fs'
import { parseEnv } from 'node:util'

/**
 * The only keys a packaged release environment may carry, in serialization
 * order: the deployment selection, its SDKWork surface URLs, the registration
 * claims the overlay materializes, the credential-store application code, and
 * the bootstrap credential. Model provider keys, operator bootstrap
 * credentials, database URLs, and public `VITE_*` / `PORTAL_PUBLIC_*` values are
 * deliberately absent and are ignored on read.
 *
 * `SDKWORK_APPLICATION_CODE` is what keeps an installed application's bundle
 * directory (`~/.sdkwork/<application-code>/credentials/`) identical to the one
 * the packaging host provisioned into: without it the Host can only guess the
 * code from its profile directory name, so a released build would look under
 * `~/.sdkwork/desktop/` while the credential lives under
 * `~/.sdkwork/birdcoder2/` and fail closed on the production tier.
 */
export const SDKWORK_RELEASE_ENV_KEYS = [
  'SDKWORK_ENVIRONMENT',
  'SDKWORK_DEPLOYMENT_PROFILE',
  'SDKWORK_PROFILE_ID',
  'SDKWORK_RUNTIME_TARGET',
  'SDKWORK_BIRDCODER_ENVIRONMENT',
  'SDKWORK_BIRDCODER_DEPLOYMENT_PROFILE',
  'SDKWORK_BIRDCODER_PROFILE_ID',
  'SDKWORK_BIRDCODER_RUNTIME_TARGET',
  'SDKWORK_BIRDCODER_PLATFORM_API_GATEWAY_HTTP_URL',
  'SDKWORK_BIRDCODER_APP_API_BASE_URL',
  'SDKWORK_BIRDCODER_APPLICATION_PUBLIC_HTTP_URL',
  'SDKWORK_IM_API_BASE_URL',
  'SDKWORK_BIRDCODER_IM_API_BASE_URL',
  'SDKWORK_IM_EMBED_URL',
  'SDKWORK_BIRDCODER_IM_EMBED_URL',
  'SDKWORK_APP_DOMAIN',
  'SDKWORK_APPLICATION_CODE',
  'SDKWORK_APP_ID',
  'SDKWORK_TENANT_ID',
  'SDKWORK_ORGANIZATION_ID',
  'SDKWORK_TENANT_APPLICATION_ID',
  'SDKWORK_ACCESS_TOKEN',
] as const

/** One key a packaged release environment may carry. */
export type SdkworkReleaseEnvKey = typeof SDKWORK_RELEASE_ENV_KEYS[number]

/** Parsed packaged release environment, split into accepted and rejected keys. */
export interface ParsedSdkworkReleaseEnv {
  /** Allowlisted non-empty values, in file order. */
  readonly values: Record<string, string>
  /** Names the file declared that this artifact may not carry. */
  readonly ignored: readonly string[]
}

/**
 * Whether a name belongs to the packaged release allowlist.
 * @param name - candidate environment key.
 * @returns true for a key a packaged release artifact may carry.
 */
export function isSdkworkReleaseEnvKey(name: string): name is SdkworkReleaseEnvKey {
  return (SDKWORK_RELEASE_ENV_KEYS as readonly string[]).includes(name)
}

/**
 * Select the allowlisted non-empty values of a resolved launch environment.
 * @param env - environment resolved from the packaging host's deployment files.
 * @returns the values a packaged release may carry, in allowlist order.
 */
export function selectSdkworkReleaseEnv(
  env: Readonly<Record<string, string | undefined>>,
): Record<string, string> {
  const selected: Record<string, string> = {}
  for (const name of SDKWORK_RELEASE_ENV_KEYS) {
    const value = env[name]?.trim()
    if (value !== undefined && value !== '') selected[name] = value
  }
  return selected
}

/**
 * Serialize the packaged release environment. Values are written verbatim:
 * an embedded line break would let one value declare another key, so it is
 * rejected instead of escaped.
 * @param values - allowlisted values, normally from {@link selectSdkworkReleaseEnv}.
 * @returns the env-file contents.
 * @throws If a value contains a carriage return or line feed.
 */
export function renderSdkworkReleaseEnv(values: Readonly<Record<string, string>>): string {
  const lines = [
    '# SDKWork packaged-release environment (private deployment artifact).',
    '# Generated by the desktop packaging lane from the packaging host\'s resolved',
    '# deployment. It carries a bootstrap credential: distribute it only with the',
    '# deployment build it was made for, and never with a public release.',
  ]
  for (const name of SDKWORK_RELEASE_ENV_KEYS) {
    const value = values[name]
    if (value === undefined || value === '') continue
    if (/[\r\n]/u.test(value)) throw new Error(`sdkwork release env: ${name} must be a single line`)
    lines.push(`${name}=${value}`)
  }
  return `${lines.join('\n')}\n`
}

/**
 * Parse a packaged release environment, keeping only the allowlisted keys.
 * @param content - env-file contents.
 * @returns accepted values plus the names that were rejected.
 */
export function parseSdkworkReleaseEnv(content: string): ParsedSdkworkReleaseEnv {
  const parsed = parseEnv(content.replace(/^\uFEFF/u, ''))
  const values: Record<string, string> = {}
  const ignored: string[] = []
  for (const [name, value] of Object.entries(parsed)) {
    if (!isSdkworkReleaseEnvKey(name)) {
      ignored.push(name)
      continue
    }
    const trimmed = value?.trim() ?? ''
    if (trimmed !== '') values[name] = trimmed
  }
  return { values, ignored }
}

/**
 * Read and parse a packaged release environment file.
 * @param path - absolute file path.
 * @returns the parsed artifact, or undefined when the file does not exist.
 * @throws When the file exists but cannot be read.
 */
export function readSdkworkReleaseEnvFile(path: string): ParsedSdkworkReleaseEnv | undefined {
  let content: string
  try {
    content = readFileSync(path, 'utf8')
  } catch (error) {
    if ((error as NodeJS.ErrnoException | null)?.code === 'ENOENT') return undefined
    throw error
  }
  return parseSdkworkReleaseEnv(content)
}

/**
 * Apply release values to a launch environment without replacing a value the
 * operator already set: the host environment outranks the packaged artifact.
 * @param values - allowlisted release values.
 * @param env - the mutable launch environment.
 * @returns the names this call filled.
 */
export function applySdkworkReleaseEnv(
  values: Readonly<Record<string, string>>,
  env: Record<string, string | undefined>,
): string[] {
  const applied: string[] = []
  for (const name of SDKWORK_RELEASE_ENV_KEYS) {
    const value = values[name]
    if (value === undefined || value === '') continue
    if (env[name]?.trim()) continue
    env[name] = value
    applied.push(name)
  }
  return applied
}

/**
 * Deployment-selection and deployment-surface keys that a caller pins a tier
 * for. A stale package or child process may export another application's
 * deployment; these are the names that must be resolved from the caller's own
 * files instead. The bootstrap credential is deliberately not included: an
 * operator-provisioned token is an input, not a deployment selection.
 */
export const SDKWORK_DEPLOYMENT_SELECTION_KEYS = [
  'SDKWORK_ENVIRONMENT',
  'SDKWORK_DEPLOYMENT_PROFILE',
  'SDKWORK_PROFILE_ID',
  'SDKWORK_RUNTIME_TARGET',
  'SDKWORK_BIRDCODER_ENVIRONMENT',
  'SDKWORK_BIRDCODER_DEPLOYMENT_PROFILE',
  'SDKWORK_BIRDCODER_PROFILE_ID',
  'SDKWORK_BIRDCODER_RUNTIME_TARGET',
  'SDKWORK_BIRDCODER_PLATFORM_API_GATEWAY_HTTP_URL',
  'SDKWORK_BIRDCODER_APP_API_BASE_URL',
  'SDKWORK_BIRDCODER_APPLICATION_PUBLIC_HTTP_URL',
  'SDKWORK_IM_API_BASE_URL',
  'SDKWORK_BIRDCODER_IM_API_BASE_URL',
  'SDKWORK_IM_EMBED_URL',
  'SDKWORK_BIRDCODER_IM_EMBED_URL',
  'SDKWORK_APP_DOMAIN',
] as const

/**
 * Copy an environment with the inherited deployment selection removed, so a
 * caller that pins a lifecycle tier resolves that tier from its own tracked and
 * overlay files even when the invoking shell inherited another deployment.
 * @param env - the invoking environment.
 * @returns a new environment without the deployment-selection keys.
 */
export function withoutInheritedSdkworkDeployment(
  env: Readonly<Record<string, string | undefined>>,
): Record<string, string | undefined> {
  const selection = new Set<string>(SDKWORK_DEPLOYMENT_SELECTION_KEYS)
  return Object.fromEntries(Object.entries(env).filter(([name]) => !selection.has(name)))
}
